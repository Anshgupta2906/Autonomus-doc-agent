
from pathlib import Path
from typing import Any

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt, RGBColor

from app.executor import TaskResult
from app.planner import Plan


OUTPUT_DIR = Path("generated_docs")


def format_value(value: Any) -> str:
    """Convert nested task output into readable document text."""

    if isinstance(value, dict):
        return "\n".join(
            f"{key.replace('_', ' ').title()}: {format_value(item)}"
            for key, item in value.items()
        )

    if isinstance(value, list):
        return "\n".join(
            f"- {format_value(item)}" for item in value
        )

    return str(value)


def generate_document(
    plan: Plan,
    results: list[TaskResult],
    request: str,
) -> Path:
    """Generate a polished Word document from agent execution results."""

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    document = Document()

    # Set page margins.
    section = document.sections[0]
    section.top_margin = Inches(0.7)
    section.bottom_margin = Inches(0.7)

    # Configure default font.
    styles = document.styles
    styles["Normal"].font.name = "Arial"
    styles["Normal"].font.size = Pt(10)

    # Title.
    title = document.add_heading(plan.title, level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    subtitle = document.add_paragraph(
        f"Document Type: {plan.document_type.replace('_', ' ').title()}"
    )
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER

    document.add_paragraph()

    # Original request.
    document.add_heading("Original Request", level=1)
    document.add_paragraph(request)

    # Executive summary.
    document.add_heading("Executive Summary", level=1)
    completed = sum(r.status == "completed" for r in results)
    failed = len(results) - completed

    document.add_paragraph(
        f"The agent planned {len(plan.tasks)} tasks and completed "
        f"{completed} successfully. {failed} task(s) failed."
    )

    # Task results.
    document.add_heading("Detailed Findings", level=1)

    for result in results:
        document.add_heading(
            f"{result.task_id}. {result.description}",
            level=2,
        )

        status = document.add_paragraph()
        status.add_run("Status: ").bold = True
        status.add_run(result.status.title())

        if result.output:
            for key, value in result.output.items():
                document.add_heading(
                    key.replace("_", " ").title(),
                    level=3,
                )
                document.add_paragraph(format_value(value))
        else:
            document.add_paragraph("No output was produced.")

    # Execution summary.
    document.add_heading("Execution Summary", level=1)
    document.add_paragraph(f"Total tasks: {len(results)}")
    document.add_paragraph(f"Completed: {completed}")
    document.add_paragraph(f"Failed: {failed}")

    if failed:
        document.add_paragraph(
            "Review failed tasks before relying on this document."
        )

    # Footer.
    for section in document.sections:
        footer = section.footer.paragraphs[0]
        footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
        footer.add_run("Generated by Autonomous Document Agent")

    # Save using a safe filename.
    safe_title = "".join(
        char if char.isalnum() or char in "-_ " else ""
        for char in plan.title
    ).strip().replace(" ", "_")[:80]

    output_path = OUTPUT_DIR / f"{safe_title or 'agent_report'}.docx"
    document.save(output_path)

    return output_path
